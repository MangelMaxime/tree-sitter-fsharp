module EasyBuild.Commands.Dev

open System
open System.ComponentModel
open System.IO
open System.Runtime.InteropServices
open Spectre.Console
open Spectre.Console.Cli
open EasyBuild
open EasyBuild.Tools

let private queries = Path.Combine(root, "queries")

/// Helix language name, Helix query directory, Zed query directory.
let private languages =
    [
        "fsharp", queries, Path.Combine(queries, "zed")
        "fsharp-signature", Path.Combine(queries, "signature"), Path.Combine(queries, "zed", "signature")
    ]

let private clearDirectory (path: string) =
    if Directory.Exists path then
        Directory.Delete(path, true)

    Directory.CreateDirectory path |> ignore

// $HELIX_RUNTIME is ignored on purpose: on some machines it points at a Helix source checkout.
let private helixRuntime =
    if RuntimeInformation.IsOSPlatform OSPlatform.Windows then
        Path.Combine(Environment.GetFolderPath Environment.SpecialFolder.ApplicationData, "helix", "runtime")
    else
        Path.Combine(Environment.GetFolderPath Environment.SpecialFolder.UserProfile, ".config", "helix", "runtime")

// Helix falls back to its built-in queries for any kind missing here, and those break this grammar.
let private helixQueryKinds =
    [ "highlights"; "injections"; "locals"; "textobjects"; "indents"; "tags"; "rainbows" ]

/// Builds both parsers and copies them with the Helix queries into the Helix runtime directory.
type DevHelixCommand() =
    inherit Command<EmptySettings>()
    interface ICommandLimiter<CommandSettings>

    override _.Execute(_, _, _) =
        Steps.build false false
        let grammars = Path.Combine(helixRuntime, "grammars")
        Directory.CreateDirectory grammars |> ignore
        File.Copy(Path.Combine(root, "parser.so"), Path.Combine(grammars, "fsharp.so"), true)

        File.Copy(
            Path.Combine(root, "signature", "parser.so"),
            Path.Combine(grammars, "fsharp-signature.so"),
            true
        )

        for language, helix, _ in languages do
            let target = Path.Combine(helixRuntime, "queries", language)
            clearDirectory target

            for scm in Directory.GetFiles(helix, "*.scm") do
                File.Copy(scm, Path.Combine(target, Path.GetFileName scm))

            for kind in helixQueryKinds do
                let stub = Path.Combine(target, kind + ".scm")

                if not (File.Exists stub) then
                    File.WriteAllText(stub, "")

        printfn $"Deployed to %s{helixRuntime} - restart Helix."
        0

// Helix's @indent/@outdent/@extend mean different things in Zed, so indents never falls back.
let private zedQueryKinds =
    [ "highlights"; "injections"; "textobjects"; "indents"; "overrides"; "brackets"; "outline" ]

/// The query files Zed loads for a language: the Zed file when it exists, else the Helix one.
let zedQuerySources (language: string) =
    let _, helix, zedQueries =
        languages |> List.find (fun (name, _, _) -> name = language)

    [
        for kind in zedQueryKinds do
            let file = kind + ".scm"
            let zedFile = Path.Combine(zedQueries, file)
            let helixFile = Path.Combine(helix, file)

            if File.Exists zedFile then
                file, zedFile
            elif kind <> "indents" && File.Exists helixFile then
                file, helixFile
    ]

let copyZedQueries (language: string) (target: string) =
    Directory.CreateDirectory target |> ignore

    for file, source in zedQuerySources language do
        File.Copy(source, Path.Combine(target, file), true)

let private zed = Path.Combine(root, "zed")
let private mirror = Path.Combine(zed, ".mirror")

let private extensionManifest (sha: string) =
    let repository = "file://" + mirror.Replace('\\', '/')

    $"""# Generated by `./build.sh dev zed` - do not edit.

id = "fsharp"
name = "F# (local dev)"
version = "0.0.1"
schema_version = 1
description = "Local development build of tree-sitter-fsharp-helix"
repository = "https://github.com/MangelMaxime/tree-sitter-fsharp-helix"
authors = ["Maxime Mangel <me@mangelmaxime.fr>"]
languages = ["languages/fsharp", "languages/fsharp-signature"]

[grammars.fsharp]
repository = "{repository}"
rev = "{sha}"

[grammars.fsharp_signature]
repository = "{repository}"
rev = "{sha}"
path = "signature"

[language_servers.fsautocomplete]
name = "FsAutoComplete"
languages = ["FSharp", "F# Signature"]

[debug_adapters.netcoredbg]
"""

/// Copies the queries into the Zed dev extension and points its manifest at a commit of the
/// current grammar sources in zed/.mirror, since Zed only fetches grammars from a git revision.
type DevZedCommand() =
    inherit Command<EmptySettings>()
    interface ICommandLimiter<CommandSettings>

    override _.Execute(_, _, _) =
        Steps.generate false false

        for language, _, _ in languages do
            copyZedQueries language (Path.Combine(zed, "languages", language))

        if not (Directory.Exists(Path.Combine(mirror, ".git"))) then
            git root [ "init"; "-q"; mirror ]
            // Lets Zed fetch an arbitrary commit over the file:// transport.
            git mirror [ "config"; "uploadpack.allowAnySHA1InWant"; "true" ]

        File.Copy(Path.Combine(root, "grammar.js"), Path.Combine(mirror, "grammar.js"), true)

        for directory in [ "src"; "signature" ] do
            let path = Path.Combine(mirror, directory)

            if Directory.Exists path then
                Directory.Delete(path, true)

        copyDirectory (Path.Combine(root, "src")) (Path.Combine(mirror, "src"))
        Directory.CreateDirectory(Path.Combine(mirror, "signature")) |> ignore

        File.Copy(
            Path.Combine(root, "signature", "grammar.js"),
            Path.Combine(mirror, "signature", "grammar.js"),
            true
        )

        copyDirectory (Path.Combine(root, "signature", "src")) (Path.Combine(mirror, "signature", "src"))
        git mirror [ "add"; "-A" ]

        let noCommit = gitCode mirror [ "rev-parse"; "-q"; "--verify"; "HEAD" ] <> 0
        let staged = gitCode mirror [ "diff"; "--cached"; "--quiet" ] <> 0

        if noCommit || staged then
            git
                mirror
                [
                    "-c"
                    "user.name=dev-zed"
                    "-c"
                    "user.email=dev-zed@localhost"
                    "commit"
                    "-qm"
                    "sync"
                ]

            printfn "Mirror updated."

        let sha = gitRead mirror [ "rev-parse"; "HEAD" ]
        File.WriteAllText(Path.Combine(zed, "extension.toml"), extensionManifest sha)
        printfn $"extension.toml -> rev %s{sha}"

        for wasm in [ "fsharp.wasm"; "fsharp_signature.wasm" ] do
            let path = Path.Combine(zed, "grammars", wasm)

            if File.Exists path then
                File.Delete path

        // Zed compiles zed/src/lib.rs itself and needs the wasm32-wasip2 target for it.
        try
            let sysroot = read "rustc" root [ "--print"; "sysroot" ]

            if not (Directory.Exists(Path.Combine(sysroot, "lib", "rustlib", "wasm32-wasip2"))) then
                AnsiConsole.MarkupLine
                    "[yellow]WARNING: Rust target wasm32-wasip2 not installed - Zed can't build the LSP glue (rustup target add wasm32-wasip2, or pacman -S rust-wasm).[/]"
        with _ ->
            ()

        printfn
            $"In Zed: Extensions panel -> Rebuild (first time: 'zed: install dev extension' -> %s{zed})"

        0

type DevNvimSettings() =
    inherit CommandSettings()

    [<CommandArgument(0, "[FILE]")>]
    [<Description("File to open (default examples/references.fsx)")>]
    member val File = "examples/references.fsx" with get, set

/// Builds the parser and opens a file in the repo-local Neovim config, bypassing ~/.config/nvim.
type DevNvimCommand() =
    inherit Command<DevNvimSettings>()
    interface ICommandLimiter<CommandSettings>

    override _.Execute(_, settings, _) =
        Steps.build false false
        run "nvim" root [ "-u"; "nvim/init.lua"; settings.File ]
        0
